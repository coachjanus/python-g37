# Потрібно обчислити квадратне значення всіх парних чисел у заданому списку. У цьому випадку ви можете використати filter() для вилучення парних чисел, а потім map() для обчислення квадратичних значень:
numbers = [1, 3, 10, 45, 6, 50]

def is_even(number):
  return number % 2 == 0

even_numbers = list(filter(is_even, numbers))
even_numbers # [10, 6, 50]

list(map(lambda n: n ** 2, even_numbers)) # [100, 36, 2500]
list(map(lambda n: n ** 2, filter(is_even, numbers))) # [100, 36, 2500]
# Є ще одна форма map(), яка приймає більше одного ітерованого аргументу:
# map(<f>, <iterablei> , <iterable₂>, ..., <iterableₙ>) - map застосовує <f> до елементів  у кожному <iterablei> паралельно та повертає ітератор, який дає результати. Кількість аргументів <iterablei>, указаних у map(), має збігатися  з кількістю аргументів, які очікує <f>. <f> діє на перший елемент кожного <iterablei>,  і цей результат стає першим елементом, який повертає ітератор. Потім <f> діє на другий елемент у кожному <iterablei>,  і він стає другим отриманим елементом і так далі.
def f(a, b, c):
  return a + b + c
list(map(f, [1, 2, 3], [10, 20, 30], [100, 200, 300])) # [111, 222, 333]
# Відповідно, для map() є три ісписки [1, 2, 3], [10, 20, 30] і [100, 200, 300].
# Перший повернутий елемент є результатом застосування f() до першого елемента  в кожному списку: f(1, 10, 100). Другим поверненим елементом є f(2, 20, 200), а третім – f(3, 30, 300)
# Значення, яке повертає map(), є ітератором, який дає список [111, 222, 333].
# ви можете замінити f() на лямбда-функцію:
list( map( (lambda a, b, c: a + b + c),  [1, 2, 3],  [10, 20, 30], [100, 200, 300]))


