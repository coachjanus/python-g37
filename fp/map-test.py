
# Функція map(<function>, iterable[, iterable1, ..., iterableN]) по черзі застосовує аргумент-функцію <function> до кожного елемента в iterable. Функція map() повертає об’єкт-ітератор. 
# Аргументи:
# <function> містить функцію перетворення. Ця функція має приймати стільки аргументів, скільки ітерацій ви передаєте в map().
# iterable містить об’єкт-ітератор, можна надати кілька об’єктів, але необов’язково.
# Функція map() застосовує <function> до кожного елемента в iterable, щоб перетворити його на інше значення з додатковими функціями. map() генерує кожен перетворений елемент на вимогу. 
# Синтаксис виклику map() для одного ітератора виглядає так: map(<f>, <iterable>)
# map(<f>, <iterable>) повертає ітератор, який є результатом застосування функції <f> до кожного елемента <iterable>.


print(list(map(lambda x: x.upper(), animals)))

txns = [1.09, 23.56, 57.66, 4.66, 6.78]

TAX_RATE = .08

def price_with_tax(tx):
    return tx * (1 + TAX_RATE)

final_prices = map(price_with_tax, txns)

print(list(final_prices))

# Функція reverse() приймає рядковий аргумент і повертає його реверс, використовуючи механізм нарізки рядків [::-1]:
def reverse(s):
  return s[::-1]
reverse("I am a string") # 'gnirts a ma I'

